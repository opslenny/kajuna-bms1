const english = Object.fromEntries(Object.keys(swahili).map((key) => [key, key]))
export const translations = { en: english, sw: swahili }

export function translate(text, language = 'en') {
  if (typeof text !== 'string') return text
  return translations[language]?.[text] || text
}
